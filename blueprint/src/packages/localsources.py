"""Build line-linked source pages for the index during leanblueprint web."""

from html import escape
from os.path import relpath
from pathlib import Path
import re
from runpy import run_path

from plasTeX.PackageResource import PackagePreCleanupCB


ROOT = Path(__file__).resolve().parents[3]
SOURCE_LINK = re.compile(
    r"sources/(material/manuscript\.tex|GaussianTesting/(?:[\w-]+/)*[\w-]+\.lean)"
    r"\.html#L([1-9][0-9]*)"
)


def source_page(path, lines, back, repository):
    title = escape(path)
    rows = "\n".join(
        f'<div class="line" id="L{n}"><a href="#L{n}" aria-label="Line {n}">{n}</a>'
        f'<code>{escape(line)}</code></div>'
        for n, line in enumerate(lines, 1)
    )
    return f"""<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title} | Blueprint source</title>
<style>
body {{margin: 1.2rem; color: #20242b; background: white; font-family: system-ui, sans-serif}}
header nav {{display: flex; align-items: center; justify-content: space-between; gap: 1rem}}
h1 {{font-size: 1.2rem; overflow-wrap: anywhere}}
main {{overflow-x: auto; font: 0.9rem/1.5 monospace}}
.line {{display: flex; width: max-content; min-width: 100%}}
.line a {{width: 4em; padding-right: 1em; flex: none; text-align: right; color: #596474; user-select: none}}
code {{white-space: pre}}
.line:target {{background: #fff1bc}}
</style>
<header><nav aria-label="Project links"><a href="{escape(back, quote=True)}">Blueprint contents</a>
<a class="repository-link" href="{escape(repository, quote=True)}" aria-label="GitHub repository">GitHub</a></nav></header>
<h1>{title}</h1>
<main>{rows}</main>
</html>
"""


def write_source_pages(document):
    # The web macro expands to an ordinary href. Collect its actual targets so
    # the source views and their line anchors always match this blueprint build.
    requested = {}
    for link in document.getElementsByTagName("href"):
        url = str(link.attributes["url"])
        if not url.startswith("sources/"):
            continue
        match = SOURCE_LINK.fullmatch(url)
        if not match:
            raise ValueError(f"Invalid local blueprint source link: {url}")
        requested.setdefault(match[1], set()).add(int(match[2]))

    pages = {}
    for path, needed in requested.items():
        source = (ROOT / path).resolve()
        if not source.is_relative_to(ROOT):
            raise ValueError(f"Source path leaves the repository: {path}")
        lines = source.read_text(encoding="utf-8").splitlines()
        if max(needed) > len(lines):
            raise ValueError(f"Source link exceeds {path}'s {len(lines)} lines")
        view = Path("sources") / (path + ".html")
        if not view.resolve().is_relative_to(Path.cwd().resolve()):
            raise ValueError(f"Source view leaves the blueprint output: {view}")
        pages[view] = source_page(path, lines, relpath("index.html", view.parent),
                                  document.userdata["project_github"])

    for view, page in pages.items():
        view.parent.mkdir(parents=True, exist_ok=True)
        view.write_text(page, encoding="utf-8")
    # Incremental builds must not publish source views for removed or no-longer
    # linked declarations. This directory is entirely generated by this package.
    for stale in Path("sources").rglob("*.html"):
        if stale not in pages:
            stale.unlink()
    return [str(view) for view in pages]


def ProcessOptions(options, document):
    document.addPackageResource([PackagePreCleanupCB(data=write_source_pages)])

    def link_lean_source():
        metadata = run_path(str(ROOT / 'scripts' / 'manuscript_map.py'))
        urls = metadata['lean_source_urls'](document.userdata.get('lean_decls', []))
        for graph in document.userdata['dep_graph']['graphs'].values():
            for node in graph.nodes:
                node.userdata['lean_urls'] = [
                    (name, urls[name]) for name in node.userdata.get('leandecls', [])]

    # leanblueprint creates its default declaration URLs at priority 150.
    document.addPostParseCallbacks(160, link_lean_source)
